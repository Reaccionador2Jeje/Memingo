#!/usr/bin/env python3
import argparse
import gzip
import hashlib
import shutil
from datetime import datetime, timezone
from email.utils import format_datetime
import subprocess
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
DIST = ROOT / "dist"
DEFAULT_OUTPUT = ROOT / "site" / "linux"


def sha256(path):
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def sha512(path):
    digest = hashlib.sha512()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def build_apt_repository(output, version, packages):
    if not shutil.which("dpkg-scanpackages"):
        print("APT repository: dpkg-scanpackages is required (install dpkg-dev)", file=sys.stderr)
        return False

    pool = output / "apt" / "pool" / "main" / "m" / "memingo"
    pool.mkdir(parents=True, exist_ok=True)
    for package in packages:
        shutil.copy2(package, pool / package.name)

    apt_root = output / "apt"
    distribution = apt_root / "dists" / "stable"
    distribution.mkdir(parents=True, exist_ok=True)

    # Discover package architectures and also publish architecture-independent
    # packages in the common Debian client architectures.
    architectures = {"amd64", "arm64", "armhf", "i386"}
    for package in packages:
        architecture = subprocess.check_output(["dpkg-deb", "-f", str(package), "Architecture"], text=True).strip()
        if architecture and architecture != "all":
            architectures.add(architecture)

    for architecture in sorted(architectures):
        component = distribution / "main" / f"binary-{architecture}"
        component.mkdir(parents=True, exist_ok=True)
        packages_file = component / "Packages"
        with packages_file.open("w", encoding="utf-8") as stream:
            subprocess.run(["dpkg-scanpackages", "--arch", architecture, "pool/", "/dev/null"], cwd=apt_root, stdout=stream, check=True)
        with packages_file.open("rb") as source, gzip.open(str(packages_file) + ".gz", "wb") as target:
            shutil.copyfileobj(source, target)

    # Let apt-ftparchive generate the canonical Release hash sections
    # (MD5Sum, SHA1, SHA256 and SHA512) instead of hand-rolling them.
    apt_ftparchive = shutil.which("apt-ftparchive")
    if not apt_ftparchive:
        print("APT repository: apt-ftparchive is required (install apt-utils)", file=sys.stderr)
        return False

    release = distribution / "Release"
    metadata = [
        "Origin: Memingo",
        "Label: Memingo",
        "Suite: stable",
        "Codename: stable",
        f"Date: {format_datetime(datetime.now(timezone.utc), usegmt=True)}",
        f"Architectures: {' '.join(sorted(architectures))}",
        "Components: main",
        "Description: Memingo APT package repository",
        "",
    ]
    result = subprocess.run(
        [apt_ftparchive, "release", "."], cwd=distribution,
        capture_output=True, text=True, check=True
    )
    hash_metadata = result.stdout
    # apt-ftparchive emits its own Date; keep our repository metadata and
    # append only the checksum sections generated by apt-ftparchive.
    for marker in ("MD5Sum:", "SHA1:", "SHA256:", "SHA512:"):
        position = hash_metadata.find(marker)
        if position >= 0:
            hash_metadata = hash_metadata[position:]
            break
    else:
        print("APT repository: apt-ftparchive produced no checksum sections", file=sys.stderr)
        return False
    release.write_text("\\n".join(metadata) + hash_metadata, encoding="utf-8")
    return True

def build_rpm_repository(output, packages):
    if not shutil.which("createrepo_c"):
        print("RPM repository: createrepo_c is required (install createrepo-c)", file=sys.stderr)
        return False

    rpm_root = output / "rpm"
    rpm_packages = rpm_root / "Packages"
    rpm_packages.mkdir(parents=True, exist_ok=True)
    for package in packages:
        shutil.copy2(package, rpm_packages / package.name)
    subprocess.run(["createrepo_c", "--update", "--database", str(rpm_root)], check=True)
    return True


def main(argv=None):
    parser = argparse.ArgumentParser(description="Create local APT and RPM repository metadata")
    parser.add_argument("--output", default=str(DEFAULT_OUTPUT))
    parser.add_argument("--only", choices=("apt", "rpm"))
    args = parser.parse_args(argv)

    output = Path(args.output).resolve()
    output.mkdir(parents=True, exist_ok=True)

    # Preserve the other repository when building only APT or RPM.
    # A full build intentionally refreshes both repositories.
    repositories_to_refresh = ("apt", "rpm") if args.only is None else (args.only,)
    for repository_name in repositories_to_refresh:
        repository_path = output / repository_name
        if repository_path.exists():
            shutil.rmtree(repository_path)

    deb_packages = sorted(DIST.glob("*.deb"))
    rpm_packages = sorted(DIST.glob("*.rpm"))
    built = []

    if args.only in (None, "apt") and deb_packages:
        if build_apt_repository(output, None, deb_packages):
            built.append(output / "apt")
    if args.only in (None, "rpm") and rpm_packages:
        if build_rpm_repository(output, rpm_packages):
            built.append(output / "rpm")

    if not built:
        print("No repository was built. Build packages first with scripts/build-packages.py", file=sys.stderr)
        return 1
    for repository in built:
        print(repository)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
